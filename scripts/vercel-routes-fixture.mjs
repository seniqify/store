// Regenerates tests/fixtures/vercel-routes.json: the route table Vercel
// compiles from vercel.json and middleware.js's matcher. It runs `vercel build`
// -- build only: nothing is deployed, and no Vercel project is read or changed
// (the copy is linked to a local-only stub) -- in a throwaway copy of this
// working tree, where it installs the dependencies itself (npm, a minute or
// two). Run it whenever vercel.json's redirects, rewrites or headers, or the
// middleware matcher, change:
//   node scripts/vercel-routes-fixture.mjs
// tests/custom-domain-routing.test.mjs fails until the fixture matches them.
import { execFileSync, execSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, copyFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const VERCEL_CLI = 'vercel@61.1.0';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'tests', 'fixtures', 'vercel-routes.json');
const tmp = mkdtempSync(join(tmpdir(), 'pl-vercel-routes-'));
try {
  const files = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z'], { cwd: root })
    .toString().split('\0').filter(Boolean);
  for (const f of files) {
    if (!existsSync(join(root, f))) continue;   // deleted in the working tree
    mkdirSync(dirname(join(tmp, f)), { recursive: true });
    copyFileSync(join(root, f), join(tmp, f));
  }
  mkdirSync(join(tmp, '.vercel'));
  writeFileSync(join(tmp, '.vercel', 'project.json'), JSON.stringify({
    projectId: 'prj_localBuildOnly', orgId: 'team_localBuildOnly',
    settings: { framework: 'vite', buildCommand: null, outputDirectory: null, installCommand: null, devCommand: null, rootDirectory: null, nodeVersion: '22.x', createdAt: 0 },
  }));
  execSync(`npx --yes ${VERCEL_CLI} build --yes`, {
    cwd: tmp, stdio: 'inherit', env: { ...process.env, VERCEL_TELEMETRY_DISABLED: '1' },
  });

  const { routes } = JSON.parse(readFileSync(join(tmp, '.vercel', 'output', 'config.json'), 'utf8'));
  const vercelJson = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'));
  const { config } = await import(pathToFileURL(join(root, 'middleware.js')).href);
  writeFileSync(out, JSON.stringify({
    about: 'Generated by scripts/vercel-routes-fixture.mjs -- do not edit. The routes `vercel build` compiled from `from`.',
    vercelCli: VERCEL_CLI,
    from: {
      redirects: vercelJson.redirects ?? [], rewrites: vercelJson.rewrites ?? [], headers: vercelJson.headers ?? [],
      matcher: config.matcher,
    },
    routes,
  }, null, 2) + '\n');
  console.log(`wrote ${out} (${routes.length} routes)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
